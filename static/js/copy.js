'use strict';

/* copy.js — the standing disclosures, defined once.

   These three strings appear in several places each: the landing, the welcome
   block, the guest banner, and under every piece of AI-generated research.
   Written inline at each site they drift — one placement gets softened, another
   gets edited for length, and the wording that a reader relies on stops being
   the wording that was agreed. There is exactly one definition of each, and
   every renderer imports it.

   All three are rendered with textContent, never innerHTML. */

/* Shown wherever a reader could mistake this tool's output for advice:
   the landing, the visitor/guest welcome, and after every research module,
   verdict and portfolio outlook. */
export const DISCLAIMER =
  'ARGUS is an educational research tool, not investment advice. Its output is '
  + 'generated by AI from public data — it can be wrong, incomplete, or out of '
  + 'date, and it is never a personalised recommendation to buy or sell anything. '
  + 'Make your own decisions and consult a licensed financial professional before acting.';

/* Sits directly under the email field, before the submit button — not behind a
   link, and not after the fact. It describes what actually happens: the row
   lands in one SQLite file on the operator's own machine and is read by nobody
   else. */
export const PRIVACY_NOTE =
  'Your email is stored only in the owner\'s private database on their own '
  + 'server, and is used for one thing: deciding whether to issue you a key. '
  + 'It is never sold, shared, or sent to any third party, and no automated '
  + 'email is ever sent. Ask the owner to delete it at any time.';

/* What the numbers on screen actually are. Surfaced on the landing, in the
   guest welcome, and in the data modal. */
export const FRESHNESS_NOTE =
  'Market data comes from Yahoo Finance and is delayed, not real-time. AI '
  + 'research runs on Perplexity with live web search when configured, or falls '
  + 'back to Groq, which has no web access and answers from model knowledge that '
  + 'may be months stale. Every research run states which provider produced it.';

/* Explains the guest allowance in the guest's own terms. Takes the live figures
   from GET /api/session so the wording can never disagree with the server. */
export function guestAllowanceLine(guest) {
  if (!guest) return '';
  const left = Math.max(0, (guest.modules_total || 0) - (guest.modules_used || 0));
  if (guest.exhausted) {
    return 'Your included deep dive is complete. Quant, charts, history, news and '
         + 'the Brent gate remain free and unlimited until your key expires.';
  }
  if (guest.dive_ticker) {
    return `Your dive is committed to ${guest.dive_ticker} — ${left} of `
         + `${guest.modules_total} stages remain. It cannot be moved to another ticker. `
         + 'Everything else here is free and unlimited.';
  }
  return `Your key includes one full ${guest.modules_total}-stage AI deep dive on a `
       + 'single ticker of your choice. Everything else — quant, charts, history, '
       + 'news, the Brent gate — is free and unlimited until your key expires.';
}
