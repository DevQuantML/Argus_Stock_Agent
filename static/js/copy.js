'use strict';

/* copy.js — the standing disclosures, defined once.

   These three strings appear in several places each: the landing, the welcome
   block, the guest banner, and under every piece of AI-generated research.
   Written inline at each site they drift — one placement gets softened, another
   gets edited for length, and the wording that a reader relies on stops being
   the wording that was agreed. There is exactly one definition of each, and
   every renderer imports it.

   All three are rendered with textContent, never innerHTML. */

/* Shown wherever a reader could mistake this tool's output for advice:
   the landing, the visitor/guest welcome, and after every research module,
   verdict and portfolio outlook. */
